//! Stands in for `claude` in tests. Replays the fixture named by
//! `KILN_FAKE_CLAUDE_FIXTURE`: recorded output lines are printed, and at each
//! recorded input line it reads one line from stdin and checks that it has
//! the same shape. A mismatch exits with status 3 and a message on stderr.

use std::io::Write as _;
use std::process::ExitCode;

use serde_json::Value;

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            let _ = writeln!(std::io::stderr(), "fake-claude: {message}");
            ExitCode::from(3)
        }
    }
}

fn run() -> Result<(), String> {
    let path = std::env::var("KILN_FAKE_CLAUDE_FIXTURE").map_err(|e| format!("fixture: {e}"))?;
    let fixture = std::fs::read_to_string(&path).map_err(|e| format!("{path}: {e}"))?;
    let mut stdin = std::io::stdin().lock();
    let mut stdout = std::io::stdout().lock();
    for record in fixture.lines() {
        let record: Value = serde_json::from_str(record).map_err(|e| e.to_string())?;
        match record["dir"].as_str() {
            Some("out") => {
                writeln!(stdout, "{}", record["msg"]).map_err(|e| e.to_string())?;
                stdout.flush().map_err(|e| e.to_string())?;
            }
            Some("in") => expect_input(&mut stdin, &record["msg"])?,
            _ => {}
        }
    }
    Ok(())
}

fn expect_input(stdin: &mut impl std::io::BufRead, expected: &Value) -> Result<(), String> {
    let mut line = String::new();
    stdin.read_line(&mut line).map_err(|e| e.to_string())?;
    let actual: Value = serde_json::from_str(&line).map_err(|e| format!("{e}: {line}"))?;
    if shape(&actual) == shape(expected) {
        Ok(())
    } else {
        Err(format!(
            "expected {}, got {}",
            shape(expected),
            shape(&actual)
        ))
    }
}

/// The parts of an input line that must match the recording. Request ids
/// generated by Kiln may differ; permission request ids and decisions may not.
fn shape(message: &Value) -> String {
    let response = &message["response"];
    format!(
        "{} {} {} {}",
        message["type"],
        message["request"]["subtype"],
        response["request_id"],
        response["response"]["behavior"],
    )
}
